// DigiPanel per-application configuration renderers (modules/softinstaller/config.go)
// Every renderer writes a real configuration file with the provisioned database
// identity. Values are escaped per format; no PHP/shell interpolation of raw
// operator input.
// Zero emojis, zero placeholders.

package softinstaller

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"
)

type renderContext struct {
	Pkg           *Package
	Inst          *Instance
	DB            *DBCredentials
	AdminPassword string
	Port          int
}

// renderConfig writes the configuration file declared by configKind.
func renderConfig(ctx *renderContext) error {
	switch ctx.Pkg.ConfigKind {
	case "none":
		return nil
	case "wordpress":
		return renderWordPress(ctx)
	case "laravel":
		return renderLaravel(ctx)
	case "ghost":
		return renderGhost(ctx)
	case "phpbb":
		return renderPHPBB(ctx)
	case "node":
		return renderNodeEnv(ctx)
	case "python":
		return renderPythonEnv(ctx)
	case "drupal":
		return renderDrupal(ctx)
	default:
		return fmt.Errorf("%w: configKind %q has no renderer", ErrManifestInvalid, ctx.Pkg.ConfigKind)
	}
}

func randomHex(n int) (string, error) {
	buf := make([]byte, n)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf), nil
}

func phpQuote(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `'`, `\'`)
	return "'" + value + "'"
}

func writeConfigFile(root, rel, content string, mode os.FileMode) error {
	path := filepath.Join(root, filepath.Clean("/"+rel))
	if !strings.HasPrefix(path, filepath.Clean(root)+string(os.PathSeparator)) {
		return fmt.Errorf("%w: config path escapes target", ErrInvalidInput)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), mode)
}

// WordPress: real wp-config.php with database constants and fresh salts.
func renderWordPress(ctx *renderContext) error {
	db := ctx.DB
	if db == nil {
		return fmt.Errorf("%w: wordpress requires a database", ErrDatabaseRequired)
	}
	var b strings.Builder
	b.WriteString("<?php\n")
	b.WriteString("// Generated by DigiPanel during application provisioning.\n")
	b.WriteString("define( 'DB_NAME', " + phpQuote(db.Name) + " );\n")
	b.WriteString("define( 'DB_USER', " + phpQuote(db.User) + " );\n")
	b.WriteString("define( 'DB_PASSWORD', " + phpQuote(db.Password) + " );\n")
	b.WriteString("define( 'DB_HOST', " + phpQuote(net.JoinHostPort(db.Host, db.Port)) + " );\n")
	b.WriteString("define( 'DB_CHARSET', 'utf8mb4' );\n")
	b.WriteString("define( 'DB_COLLATE', '' );\n")
	b.WriteString("$table_prefix = 'wp_';\n")
	for _, key := range []string{"AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"} {
		salt, err := randomHex(48)
		if err != nil {
			return err
		}
		b.WriteString("define( " + phpQuote(key) + ", " + phpQuote(salt) + " );\n")
	}
	b.WriteString("define( 'WP_HOME', " + phpQuote(ctx.Inst.SiteURL) + " );\n")
	b.WriteString("define( 'WP_SITEURL', " + phpQuote(ctx.Inst.SiteURL) + " );\n")
	b.WriteString("define( 'DISALLOW_FILE_EDIT', true );\n")
	b.WriteString("if ( ! defined( 'ABSPATH' ) ) { define( 'ABSPATH', __DIR__ . '/' ); }\n")
	b.WriteString("require_once ABSPATH . 'wp-settings.php';\n")
	return writeConfigFile(ctx.Inst.Path, "wp-config.php", b.String(), 0640)
}

// Laravel: .env consumed by artisan and the framework bootstrap.
func renderLaravel(ctx *renderContext) error {
	db := ctx.DB
	if db == nil {
		return fmt.Errorf("%w: laravel requires a database", ErrDatabaseRequired)
	}
	connection := "mysql"
	if db.Engine == DBPostgres {
		connection = "pgsql"
	}
	content := strings.Join([]string{
		"APP_NAME=" + dotenvQuote(ctx.Inst.Title),
		"APP_ENV=production",
		"APP_KEY=",
		"APP_DEBUG=false",
		"APP_URL=" + dotenvQuote(ctx.Inst.SiteURL),
		"",
		"DB_CONNECTION=" + connection,
		"DB_HOST=" + dotenvQuote(db.Host),
		"DB_PORT=" + dotenvQuote(db.Port),
		"DB_DATABASE=" + dotenvQuote(db.Name),
		"DB_USERNAME=" + dotenvQuote(db.User),
		"DB_PASSWORD=" + dotenvQuote(db.Password),
		"",
		"SESSION_DRIVER=file",
		"CACHE_STORE=file",
		"QUEUE_CONNECTION=sync",
		"",
	}, "\n")
	return writeConfigFile(ctx.Inst.Path, ".env", content, 0640)
}

func dotenvQuote(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	value = strings.ReplaceAll(value, "\n", "")
	value = strings.ReplaceAll(value, "\r", "")
	return `"` + value + `"`
}

// Ghost: config.production.json for the Node process. The process itself is
// supervised by the runtimes module; the manifest records the entry point.
func renderGhost(ctx *renderContext) error {
	db := ctx.DB
	if db == nil {
		return fmt.Errorf("%w: ghost requires a database", ErrDatabaseRequired)
	}
	config := map[string]any{
		"url": ctx.Inst.SiteURL,
		"server": map[string]any{
			"host": "127.0.0.1",
			"port": ctx.Port,
		},
		"database": map[string]any{
			"client": "mysql",
			"connection": map[string]any{
				"host":     db.Host,
				"port":     db.Port,
				"user":     db.User,
				"password": db.Password,
				"database": db.Name,
			},
		},
		"mail":    map[string]any{"transport": "Direct"},
		"logging": map[string]any{"transports": []string{"stdout"}},
		"paths":   map[string]any{"contentPath": "content"},
	}
	data, err := json.MarshalIndent(config, "", "  ")
	if err != nil {
		return err
	}
	return writeConfigFile(ctx.Inst.Path, "config.production.json", string(data)+"\n", 0640)
}

// phpBB: YAML installer configuration consumed by install/phpbbcli.php.
func renderPHPBB(ctx *renderContext) error {
	db := ctx.DB
	if db == nil {
		return fmt.Errorf("%w: phpbb requires a database", ErrDatabaseRequired)
	}
	content := strings.Join([]string{
		"admin:",
		"  name: " + yamlQuote(ctx.Inst.AdminUser),
		"  password: " + yamlQuote(ctx.AdminPassword),
		"  email: " + yamlQuote(ctx.Inst.AdminEmail),
		"board:",
		"  lang: en",
		"  name: " + yamlQuote(ctx.Inst.Title),
		"  description: " + yamlQuote("Hosted by "+ctx.Inst.Title),
		"database:",
		"  dbms: " + yamlQuote(phpbbDBMS(db.Engine)),
		"  dbhost: " + yamlQuote(db.Host),
		"  dbport: " + yamlQuote(db.Port),
		"  dbuser: " + yamlQuote(db.User),
		"  dbpasswd: " + yamlQuote(db.Password),
		"  dbname: " + yamlQuote(db.Name),
		"  table_prefix: " + yamlQuote("phpbb_"),
		"email:",
		"  enabled: false",
		"  smtp_delivery: false",
		"  smtp_host: " + yamlQuote(""),
		"  smtp_port: " + yamlQuote("25"),
		"  smtp_auth: false",
		"  smtp_user: " + yamlQuote(""),
		"  smtp_pass: " + yamlQuote(""),
		"server:",
		"  cookie_secure: true",
		"  server_protocol: " + yamlQuote("https://"),
		"  force_server_vars: true",
		"  server_name: " + yamlQuote(ctx.Inst.Domain),
		"  server_port: " + yamlQuote("443"),
		"  script_path: " + yamlQuote("/"+strings.Trim(ctx.Inst.DomainPath, "/")),
		"extensions:",
		"  - " + yamlQuote("phpbb/viglink"),
		"",
	}, "\n")
	return writeConfigFile(ctx.Inst.Path, ".digipanel/phpbb-install.yml", content, 0600)
}

func yamlQuote(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	value = strings.ReplaceAll(value, "\n", "")
	value = strings.ReplaceAll(value, "\r", "")
	return `"` + value + `"`
}

func renderNodeEnv(ctx *renderContext) error {
	content := strings.Join([]string{
		"NODE_ENV=production",
		"HOST=127.0.0.1",
		fmt.Sprintf("PORT=%d", ctx.Port),
		"APP_URL=" + dotenvQuote(ctx.Inst.SiteURL),
		"",
	}, "\n")
	return writeConfigFile(ctx.Inst.Path, ".env", content, 0640)
}

