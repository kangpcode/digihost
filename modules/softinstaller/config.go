// renderInstallMetadata records non-secret facts used by clone/update/UI.
func renderInstallMetadata(ctx *renderContext) error {
	meta := map[string]any{
		"packageId":      ctx.Pkg.ID,
		"packageName":    ctx.Pkg.Name,
		"packageVersion": ctx.Pkg.LatestVersion,
		"siteURL":        ctx.Inst.SiteURL,
		"domain":         ctx.Inst.Domain,
		"domainPath":     ctx.Inst.DomainPath,
		"adminPath":      ctx.Pkg.AdminPath,
		"installedAt":    ctx.Inst.CreatedAt,
	}
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	return writeConfigFile(ctx.Inst.Path, ".digipanel/instance.json", string(data)+"\n", 0600)
}

// Drupal: settings.php with the provisioned database so the web installer only
// has to create the schema and the first account.
func renderDrupal(ctx *renderContext) error {
	db := ctx.DB
	if db == nil {
		return fmt.Errorf("%w: drupal requires a database", ErrDatabaseRequired)
	}
	driver := "mysql"
	if db.Engine == DBPostgres {
		driver = "pgsql"
	}
	salt, err := randomHex(48)
	if err != nil {
		return err
	}
	content := fmt.Sprintf(`<?php
// Generated by DigiPanel during application provisioning.
$databases['default']['default'] = [
  'database' => %s,
  'username' => %s,
  'password' => %s,
  'host' => %s,
  'port' => %s,
  'driver' => %s,
  'prefix' => '',
];
$settings['hash_salt'] = %s;
$settings['config_sync_directory'] = 'sites/default/files/config';
$settings['update_free_access'] = FALSE;
$settings['file_private_path'] = 'sites/default/files/private';
if (file_exists(__DIR__ . '/settings.local.php')) {
  include __DIR__ . '/settings.local.php';
}
`, phpQuote(db.Name), phpQuote(db.User), phpQuote(db.Password), phpQuote(db.Host), phpQuote(db.Port), phpQuote(driver), phpQuote(salt))
	if err := writeConfigFile(ctx.Inst.Path, "sites/default/settings.php", content, 0640); err != nil {
		return err
	}
	for _, dir := range []string{"sites/default/files", "sites/default/files/config", "sites/default/files/private"} {
		if err := os.MkdirAll(filepath.Join(ctx.Inst.Path, filepath.FromSlash(dir)), 0755); err != nil {
			return err
		}
	}
	return nil
}

func phpbbDBMS(engine string) string {
	if engine == DBPostgres {
		return "postgres"
	}
	return "mysqli"
}
